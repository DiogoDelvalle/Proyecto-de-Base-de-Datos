los atributos: C�digo y descripci�n del Producto, c�digo y nombre del proveedor.*/
SELECT 
    p.ID_PRODUCTO AS CODIGO_PRODUCTO,
    p.DESCRIPCION AS PRODUCTO,
    pr.ID_PROVEEDORES AS CODIGO_PROVEEDOR,
    pr.NOMBRE AS PROVEEDOR
FROM PRODUCTOS p
JOIN DETALLES_DEL_PRODUCTO dp ON p.ID_PRODUCTO = dp.ID_PRODUCTO
JOIN FACTURAS f ON dp.ID_FACTURAS = f.ID_FACTURAS
JOIN PROVEEDORES pr ON f.ID_PROVEEDORES = pr.ID_PROVEEDORES
WHERE p.ID_PRODUCTO IN (
    SELECT dp2.ID_PRODUCTO
    FROM DETALLES_DEL_PRODUCTO dp2
    JOIN FACTURAS f2 ON dp2.ID_FACTURAS = f2.ID_FACTURAS
    GROUP BY dp2.ID_PRODUCTO
    HAVING COUNT(DISTINCT f2.ID_PROVEEDORES) > 1
)
ORDER BY p.ID_PRODUCTO, pr.ID_PROVEEDORES;
GO
