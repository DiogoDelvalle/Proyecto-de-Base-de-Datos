CREATE OR ALTER PROCEDURE BajaDetalleOrdenPago
    @ID_DETALLE_ORDEN INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_ORDEN INT;

    SELECT @ID_ORDEN = ID_ORDEN FROM DETALLES_DE_ORDENES_DE_PAGO WHERE ID_DETALLE_ORDEN = @ID_DETALLE_ORDEN;

    IF @ID_ORDEN IS NULL
    BEGIN
        RAISERROR('El detalle con ID %d no existe.', 16, 1, @ID_DETALLE_ORDEN);
        RETURN;
    END

    DELETE FROM DETALLES_DE_ORDENES_DE_PAGO WHERE ID_DETALLE_ORDEN = @ID_DETALLE_ORDEN;

    UPDATE ORDENES_DE_PAGO
    SET TOTAL_ORDEN = (
        SELECT COALESCE(SUM(TOTAL), 0)
        FROM DETALLES_DE_ORDENES_DE_PAGO
        WHERE ID_ORDEN = @ID_ORDEN
    )
    WHERE ID_ORDEN = @ID_ORDEN;
END;
GO
