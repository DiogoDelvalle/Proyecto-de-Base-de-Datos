CREATE OR ALTER PROCEDURE ModificarDetalleOrdenPago
    @ID_DETALLE_ORDEN INT,
    @ID_FACTURAS INT,
    @TOTAL NUMERIC(11)
AS
BEGIN
    SET NOCOUNT ON;

    -- Actualizar el detalle
    UPDATE DETALLES_DE_ORDENES_DE_PAGO
    SET ID_FACTURAS = @ID_FACTURAS,
        TOTAL = @TOTAL
    WHERE ID_DETALLE_ORDEN = @ID_DETALLE_ORDEN;

    IF @@ROWCOUNT = 0
    BEGIN
        RAISERROR('No se encontró el detalle de orden con ID %d.', 16, 1, @ID_DETALLE_ORDEN);
        RETURN;
    END

    -- Actualizar el total de la orden
    DECLARE @ID_ORDEN INT;
    SELECT @ID_ORDEN = ID_ORDEN FROM DETALLES_DE_ORDENES_DE_PAGO WHERE ID_DETALLE_ORDEN = @ID_DETALLE_ORDEN;

    UPDATE ORDENES_DE_PAGO
    SET TOTAL_ORDEN = (
        SELECT COALESCE(SUM(TOTAL), 0)
        FROM DETALLES_DE_ORDENES_DE_PAGO
        WHERE ID_ORDEN = @ID_ORDEN
    )
    WHERE ID_ORDEN = @ID_ORDEN;
END;
GO
