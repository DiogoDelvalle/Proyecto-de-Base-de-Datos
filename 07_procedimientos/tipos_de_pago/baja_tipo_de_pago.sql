CREATE OR ALTER PROCEDURE BajaTipoDePago
    @ID_TIPO INT
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM ORDENES_TIPOS_DE_PAGO WHERE ID_TIPO = @ID_TIPO)
    BEGIN
        RAISERROR('El tipo de pago con ID %d no existe.', 16, 1, @ID_TIPO);
        RETURN;
    END

    DELETE FROM ORDENES_TIPOS_DE_PAGO WHERE ID_TIPO = @ID_TIPO;
END;
GO
