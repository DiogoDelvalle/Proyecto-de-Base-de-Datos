CREATE OR ALTER PROCEDURE AltaTipoDePago
    @ID_ORDEN INT,
    @TIPO_DE_PAGO VARCHAR(100),
    @MONTO_DE_PAGO NUMERIC(9)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM ORDENES_DE_PAGO WHERE ID_ORDEN = @ID_ORDEN)
    BEGIN
        RAISERROR('La orden con ID %d no existe.', 16, 1, @ID_ORDEN);
        RETURN;
    END

    INSERT INTO ORDENES_TIPOS_DE_PAGO (ID_ORDEN, TIPO_DE_PAGO, MONTO_DE_PAGO)
    VALUES (@ID_ORDEN, @TIPO_DE_PAGO, @MONTO_DE_PAGO);
END;
GO
