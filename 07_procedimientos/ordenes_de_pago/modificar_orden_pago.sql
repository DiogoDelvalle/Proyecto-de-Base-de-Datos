CREATE OR ALTER PROCEDURE ModificarOrdenPago
    @ID_ORDEN INT,
    @TOTAL_ORDEN NUMERIC(12,2),
    @FECHA_ORDEN DATE,
    @DESCRIPCION VARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE ORDENES_DE_PAGO
    SET FECHA_ORDEN = @FECHA_ORDEN,
        DESCRIPCION = @DESCRIPCION,
        TOTAL_ORDEN = @TOTAL_ORDEN
    WHERE ID_ORDEN = @ID_ORDEN;

    IF @@ROWCOUNT = 0
    BEGIN
        RAISERROR('No se encontró la orden con ID %d.', 16, 1, @ID_ORDEN);
    END
END;
GO
