/*Facturas de proveedores vencidas*/
CREATE VIEW VIEW_FACTURAS_VENCIDAS AS 
SELECT 
    f.ID_FACTURAS,
    p.NOMBRE AS PROVEEDOR,
    f.FECHA_COMPRA,
    f.FECHA_VENCIMIENTO,
    f.TOTAL,
    f.CONDICION_COMPRA
FROM FACTURAS f
JOIN PROVEEDORES p 
    ON f.ID_PROVEEDORES = p.ID_PROVEEDORES
WHERE f.FECHA_VENCIMIENTO < GETDATE();
GO
